"""tieoff.py - drive a DUT's unused INPUTS, and never its outputs.

WHY THIS EXISTS (bug 29)
------------------------
The probes started with this sweep:

    for name in dir(dut):
        if name.endswith("ready") or name.endswith("ack"):
            getattr(dut, name).value = 1

The intent was right - a permanently-low ready on a core-mastered interface
stalls the design, and doing it by port family beats doing it one port at a
time. The execution was wrong: `dir(dut)` returns ALL ports, and 13 of
mqnic_core_pcie's ready/ack ports are OUTPUTS. Forcing a value onto a driven
net is contention, and contention is X.

Two of those outputs sit directly on the register path (m_axil_csr_bready,
m_axil_csr_rready) and one is the handshake the probe itself reads to decide the
request was accepted (pcie_rx_req_tlp_ready). The resulting X reached
axil_reg_if_rd, whose load condition is

    if (!s_axil_arvalid_reg) s_axil_arvalid_next = s_axil_arvalid;

so once s_axil_arvalid_reg held X it could never reload. One contended output
disabled the register interface for the whole simulation, and the symptom -
"a BAR read is accepted and never completes" - pointed at the DUT.

THE RULE
--------
Direction comes from the RTL, never from the signal name. gen_tb_ports.py has
said this since Tier 5 started ("inputs the DUT reads -> DRIVE, outputs the DUT
drives -> SINK"); this module is the same rule for the cocotb side.
"""

import pathlib
import re

PORT_RE = re.compile(
    r"^\s*(input|output|inout)\s+(?:wire|reg|logic)?\s*"
    r"(\[[^\]]*\]\s*)?([A-Za-z_]\w*)\s*[,)]?\s*(?://.*)?$")


def port_directions(rtl_path, module):
    """Return {port_name: 'input'|'output'|'inout'} from the module header."""
    text = pathlib.Path(rtl_path).read_text(encoding="utf-8", errors="replace")
    m = re.search(rf"^module\s+{re.escape(module)}\b", text, re.M)
    if not m:
        raise ValueError(f"module {module} not found in {rtl_path}")
    end = text.find("\n);", m.start())
    header = text[m.start():end if end > 0 else len(text)]
    out = {}
    for line in header.splitlines():
        p = PORT_RE.match(line)
        if p:
            out[p.group(3)] = p.group(1)
    return out


def drive_all_inputs(dut, rtl_path, module, skip=(), log=None):
    """Drive EVERY input the test does not own. Floating inputs are X, and X
    spreads.

    WHY THIS AND NOT JUST THE HANDSHAKES (bug 30)
    ---------------------------------------------
    The SystemVerilog top (tb/tb_top_tier5.sv) is generated by
    sim/scripts/gen_tb_ports.py, which ties off all 250 ports precisely so that
    "unconnected" is a decision rather than an omission. The cocotb runner
    drives mqnic_core_pcie directly, with no port map at all - so every input
    the test did not name was floating.

    Two of them are ctrl_reg_rd_data and ctrl_reg_rd_wait, the application
    register extension. mqnic_core.v:752-753 ORs them straight into the
    register interface:

        assign ctrl_reg_rd_data_int = ctrl_reg_rd_data | ctrl_reg_rd_data_reg | ...
        assign ctrl_reg_rd_wait_int = ctrl_reg_rd_wait | ...

    X | anything is X, so leaving one 1-bit input floating made the core's whole
    register file return X - including the FW ID block a BAR read is trying to
    reach. The design was never at fault.

    POLICY: *ready high, EVERYTHING ELSE LOW - INCLUDING *ack (bug 32)
    ------------------------------------------------------------------
    *ready and *ack look like one family and are not.

      *ready is pure flow control. Tying it high says "the peer always accepts",
      which is exactly right for an absent peer: nothing stalls and no data is
      invented.

      *ack says "a slave has ANSWERED THIS TRANSACTION", and it travels with a
      data bus. mqnic_core.v:754 is the case that matters:

          assign ctrl_reg_rd_ack_int  = ctrl_reg_rd_ack | ctrl_reg_rd_ack_reg | ...
          assign ctrl_reg_rd_data_int = ctrl_reg_rd_data | ctrl_reg_rd_data_reg | ...

      ctrl_reg_rd_ack is the APPLICATION register extension's acknowledge. Tied
      high, the absent application answers every register read instantly, and it
      answers with its tied-off data of 0 - beating the core's own register file,
      which needs a cycle to respond. Every read returned 0x00000000, including
      the FW ID type that must read 0xFFFFFFFF.

      That failure is worse than a stall: the walk COMPLETED, three reads
      "succeeded", and every value was wrong. A tie-off that invents responses
      is indistinguishable from a DUT that answers incorrectly.

    Tying *ack low is safe: axil_reg_if has a TIMEOUT (4 cycles), so a read that
    genuinely has no responder still completes rather than hanging.
    """
    dirs = port_directions(rtl_path, module)
    skip = set(skip)
    driven_hi, driven_lo, failed = [], [], []
    for name, d in dirs.items():
        if d != "input" or name in skip:
            continue
        n = name.lower()
        hi = n.endswith("ready")        # NOT *ack - see the note below
        try:
            getattr(dut, name).value = 1 if hi else 0
            (driven_hi if hi else driven_lo).append(name)
        except Exception:
            failed.append(name)
    if log:
        log.info(f"tie-off: {len(driven_hi)} input(s) high, {len(driven_lo)} low, "
                 f"{len(skip)} owned by the test, {len(failed)} failed")
        if failed:
            log.warning(f"tie-off could not drive: {', '.join(failed[:10])}")
    return driven_hi, driven_lo, failed


def drive_ready_inputs(dut, rtl_path, module, log=None):
    """Drive every INPUT named *ready / *ack high; leave outputs strictly alone.

    Returns (driven, skipped_outputs) so a test can assert on the counts - a
    silently-empty sweep is how this went wrong the first time.
    """
    dirs = port_directions(rtl_path, module)
    driven, skipped = [], []
    for name, d in dirs.items():
        n = name.lower()
        if not (n.endswith("ready") or n.endswith("ack")):
            continue
        if d != "input":
            skipped.append(name)
            continue
        try:
            getattr(dut, name).value = 1
            driven.append(name)
        except Exception:
            pass
    if log:
        log.info(f"tie-off: drove {len(driven)} ready/ack INPUT(s), "
                 f"left {len(skipped)} output(s) alone")
    return driven, skipped


async def power_on_reset(dut, rst, clk_edge, cycles=16):
    """Assert reset, release, RE-ASSERT, release. Not superstition - required.

    WHY THE SECOND PULSE (bug 31)
    -----------------------------
    IEEE 1364 `always @*` is an event control: the block WAITS for a change
    before it first executes. A combinational block whose inputs never change
    therefore never runs, and its outputs keep the X they started with.

    Alex Forencich's AXI library is full of the pattern

        reg x_reg = 1'b0, x_next;      // x_next has no initialiser
        always @* x_next = x_reg;      // fires only when something changes
        always @(posedge clk) if (rst) x_reg <= 1'b0; else x_reg <= x_next;

    In a quiescent design at start-up nothing changes, so x_next stays X while
    reset holds x_reg at 0 - and the moment reset is released, x_reg <= X.
    From there the X is self-sustaining, because x_next is computed from x_reg.

    That is exactly what stalled the Tier 5 BAR path: every axil_register_rd in
    the AXI-Lite tree came out of reset with an X valid, so a register read was
    accepted, decoded, matched to its region, and then never completed.

    The first release makes x_reg change (0 -> X), which is the event the block
    was waiting for. Re-asserting reset then drives x_reg back to a known 0 and
    the now-live block recomputes x_next = 0. The second release starts clean.

    `always_comb` is guaranteed to execute once at time zero and would not need
    this; `always @*` is not, and this RTL is Verilog-2001. Simulators differ in
    whether they evaluate @* at time zero, which is why the design works on some
    tools and not others - and why the fix belongs in the testbench rather than
    in RTL that hardware is known to run.
    """
    rst.value = 1
    for _ in range(cycles):
        await clk_edge()
    rst.value = 0                      # release #1 - creates the event
    for _ in range(4):
        await clk_edge()
    rst.value = 1                      # re-assert - blocks now recompute clean
    for _ in range(cycles):
        await clk_edge()
    rst.value = 0                      # release #2 - the real one
    for _ in range(cycles):
        await clk_edge()
