#!/usr/bin/env python3
"""gen_regress_lists.py - regenerate sim/regress/*.list from the test sources.

Implements : VERIFICATION_STRATEGY.md  §16.4, §19 E1/E7

WHY THIS IS GENERATED RATHER THAN HAND-MAINTAINED
-------------------------------------------------
A regression list is a hand-maintained inventory, and this project has already
been bitten once by exactly that: check_filelists.py kept its tier table by hand,
a rename missed it, and the script SILENTLY STOPPED CHECKING a whole tier while
still reporting OK (bug 20).

A regression list fails the same way and worse - a test that is written, passes,
and is never added to the list contributes nothing and nobody notices, because
there is no error to see. The list just gets shorter than the suite.

So the lists are derived from the registered test classes, and --check makes CI
fail if they have drifted.

Usage:
    python gen_regress_lists.py            # rewrite the lists
    python gen_regress_lists.py --check    # exit 1 if they are stale
"""

import argparse
import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TESTS = ROOT / "tests"
REGRESS = ROOT / "sim" / "regress"

# Directory under tests/ -> tier id used by the Makefile and the filelists.
TIER_DIR = collections.OrderedDict([
    ("tier1a", "1a"), ("tier1b", "1b"), ("tier1c", "1c"),
    ("tier2",  "2"),
    ("tier3",  "3"),  ("tier3b", "3b"), ("tier3c", "3c"),
    ("tier4a", "4a"), ("tier4b", "4b"), ("tier4c", "4c"),
    ("tier4d", "4d"),
    ("tier5",  "5"),
    ("tier6",  "6"),
])

# A registered test class. Base classes are excluded: they are abstract and
# running one proves nothing.
TEST_RE = re.compile(r"`uvm_component_utils\((t[0-9][a-z0-9_]*)\)")

HEADER = """# {title}
# Implements : VERIFICATION_STRATEGY.md  §16.4, §19 E1
#
# Format: <tier> <test> [seed ...]. With no seed, --seeds applies.
#
# GENERATED by sim/scripts/gen_regress_lists.py - do not edit by hand.
# Run that script with --check in CI: a test that exists but is not listed
# contributes nothing and produces no error, so the list has to be derived
# rather than remembered. See bug 20 in docs/bringup_log.md.
"""


def discover():
    found = collections.OrderedDict()
    for d, tier in TIER_DIR.items():
        p = TESTS / d
        if not p.is_dir():
            continue
        tests = []
        for sv in sorted(p.glob("*.sv")):
            for m in TEST_RE.finditer(sv.read_text(encoding="utf-8")):
                name = m.group(1)
                if name.endswith("_base_test"):
                    continue
                if name not in tests:
                    tests.append(name)
        if tests:
            found[tier] = tests
    return found


def render(found):
    out = {}
    for tier, tests in found.items():
        body = [HEADER.format(title=f"Tier {tier} regression list.")]
        body += [f"{tier} {t}" for t in tests]
        out[f"tier{tier}.list"] = "\n".join(body) + "\n"

    night = [HEADER.format(title="Nightly regression - every tier currently building.")]
    night += ["# §19 E7 asks for three consecutive green nights. No tier has met",
              "# its gate yet, so this is the CANDIDATE list, not a signoff list.", ""]
    for tier, tests in found.items():
        night.append(f"# ---- Tier {tier} ----")
        night += [f"{tier} {t}" for t in tests]
    out["nightly.list"] = "\n".join(night) + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the lists are stale, without rewriting them")
    args = ap.parse_args()

    found = discover()
    rendered = render(found)
    total = sum(len(v) for v in found.values())

    stale = []
    for name, text in rendered.items():
        p = REGRESS / name
        if not p.is_file() or p.read_text(encoding="utf-8") != text:
            stale.append(name)

    if args.check:
        if stale:
            print("STALE regression list(s):", ", ".join(stale))
            print("Run: python sim/scripts/gen_regress_lists.py")
            return 1
        print(f"regression lists up to date: {total} test(s) across {len(found)} tier(s)")
        return 0

    REGRESS.mkdir(parents=True, exist_ok=True)
    for name, text in rendered.items():
        (REGRESS / name).write_text(text, encoding="utf-8")
    for tier, tests in found.items():
        print(f"  tier{tier}.list : {len(tests)} test(s)")
    print(f"  nightly.list  : {total} test(s) across {len(found)} tier(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
