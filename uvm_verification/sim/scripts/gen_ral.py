#!/usr/bin/env python3
"""gen_ral.py - generate the register model from modules/mqnic/mqnic_hw.h.

Implements : VERIFICATION_STRATEGY.md  §8 (RAL), §8.2 (block discovery)
Introduced : Step 7 (Tier 5)

WHY GENERATED
-------------
§8.1 is explicit: do not hand-transcribe. mqnic_hw.h is the driver's view of the
hardware and it moves with the RTL; a hand-written RAL goes stale silently and
then the testbench and the driver disagree about the device.

This is the same argument as gen_regress_lists.py, and the same failure mode as
bug 20: an inventory maintained by memory stops covering what it forgets, and
says nothing when it does.

WHAT THIS IS NOT
----------------
NOT a uvm_reg_block with fixed offsets. Corundum's map is a WALKED LINKED LIST
of register blocks (§8.2):

    +0x00  type      block type ID
    +0x04  version
    +0x08  next_ptr  offset of the next block, 0 terminates

Block addresses are DISCOVERED at run time and depend on how the DUT was
parameterised. A flat RAL would bake in one particular build's layout and would
be wrong for every other one - and would hide exactly the bug (a block at the
wrong offset, or missing) that walking the list is there to find.

So what is generated is:
  * the block TYPE IDs and their register OFFSETS WITHIN a block, which are
    fixed by the header and are what the driver relies on;
  * a lookup from type ID to a human name and its register table.

The BASE ADDRESS of each block is supplied at run time by the walker
(mqnic_rb_walker in the RAL package), not by this script.

Usage:
    python gen_ral.py                 # write ral/mqnic_ral_pkg.sv
    python gen_ral.py --check         # exit 1 if the generated file is stale
"""

import argparse
import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HW_H = ROOT.parent / "modules" / "mqnic" / "mqnic_hw.h"
OUT = ROOT / "ral" / "mqnic_ral_pkg.sv"

DEFINE_RE = re.compile(r"^#define\s+(MQNIC_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)\s*$", re.M)
TYPE_RE = re.compile(r"^MQNIC_RB_([A-Z0-9_]+)_TYPE$")
VER_RE = re.compile(r"^MQNIC_RB_([A-Z0-9_]+)_VER$")
REG_RE = re.compile(r"^MQNIC_RB_([A-Z0-9_]+)_REG_([A-Z0-9_]+)$")


def parse():
    if not HW_H.is_file():
        print(f"cannot find {HW_H}", file=sys.stderr)
        sys.exit(2)
    text = HW_H.read_text(encoding="utf-8", errors="replace")
    defs = {m.group(1): int(m.group(2), 0) for m in DEFINE_RE.finditer(text)}

    blocks = collections.OrderedDict()
    for name, val in defs.items():
        m = TYPE_RE.match(name)
        # MQNIC_RB_REG_TYPE is the offset of the type field itself, not a block.
        if m and name != "MQNIC_RB_REG_TYPE":
            blocks.setdefault(m.group(1), {"type": val, "ver": None, "regs": {}})
    for name, val in defs.items():
        m = VER_RE.match(name)
        if m and m.group(1) in blocks:
            blocks[m.group(1)]["ver"] = val
    for name, val in defs.items():
        m = REG_RE.match(name)
        if m and m.group(1) in blocks:
            blocks[m.group(1)]["regs"][m.group(2)] = val

    common = {k: defs[k] for k in ("MQNIC_RB_REG_TYPE", "MQNIC_RB_REG_VER",
                                   "MQNIC_RB_REG_NEXT_PTR") if k in defs}
    return defs, blocks, common


def render(defs, blocks, common):
    L = []
    a = L.append
    a("// SPDX-License-Identifier: BSD-2-Clause-Views")
    a("//")
    a("// mqnic_ral_pkg - register model, GENERATED from modules/mqnic/mqnic_hw.h")
    a("// " + "-" * 75)
    a("// Implements : VERIFICATION_STRATEGY.md  §8 (RAL), §8.2 (block discovery)")
    a("//")
    a("// GENERATED by sim/scripts/gen_ral.py - do not edit. Regenerate after any")
    a("// change to mqnic_hw.h, and run with --check in CI: a hand-maintained")
    a("// register model goes stale silently, and then the testbench and the Linux")
    a("// driver disagree about the device.")
    a("//")
    a("// THIS IS NOT A FLAT uvm_reg_block, and that is deliberate (§8.2).")
    a("// Corundum's map is a WALKED LINKED LIST: each block carries its type, its")
    a("// version and the offset of the next one, and where a block LANDS depends")
    a("// on how the DUT was parameterised. Baking one build's offsets into the")
    a("// model would make it wrong for every other build, and would hide the very")
    a("// bug - a block missing or at the wrong offset - that walking the list")
    a("// exists to find.")
    a("//")
    a("// What is fixed, and therefore generated here, is the offset of each")
    a("// register WITHIN its block, plus the type IDs. Base addresses come from")
    a("// the walker at run time.")
    a("// " + "-" * 75)
    a("")
    a("`timescale 1ns / 1ps")
    a("")
    a("package mqnic_ral_pkg;")
    a("")
    a("    // ---- the three fields every block header carries (§8.2) -------------")
    for k, v in common.items():
        a(f"    localparam int unsigned {k[6:]:<24} = 'h{v:02X};")
    a("")
    a(f"    // ---- {len(blocks)} block types -------------------------------------------")
    a("    typedef enum bit [31:0] {")
    items = [(n, b["type"]) for n, b in blocks.items()]
    for i, (n, t) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        a(f"        RB_{n:<22} = 32'h{t:08X}{comma}")
    a("    } mqnic_rb_type_e;")
    a("")
    a("    // ---- register offsets within each block ------------------------------")
    for n, b in blocks.items():
        if not b["regs"]:
            continue
        a(f"    // {n}  (type 0x{b['type']:08X}" +
          (f", version 0x{b['ver']:08X})" if b["ver"] is not None else ")"))
        for r, off in sorted(b["regs"].items(), key=lambda kv: kv[1]):
            a(f"    localparam int unsigned RB_{n}_{r:<20} = 'h{off:02X};")
        a("")
    a("    // ---- a block's expected version, for the discovery check -------------")
    a("    function automatic bit [31:0] rb_expected_version(mqnic_rb_type_e t);")
    a("        case (t)")
    for n, b in blocks.items():
        if b["ver"] is not None:
            a(f"            RB_{n}: return 32'h{b['ver']:08X};")
    a("            default: return 32'h0000_0000;   // no version declared")
    a("        endcase")
    a("    endfunction")
    a("")
    a("    function automatic string rb_type_name(bit [31:0] t);")
    a("        case (t)")
    for n, b in blocks.items():
        a(f'            32\'h{b["type"]:08X}: return "{n}";')
    a('            default: return "UNKNOWN";')
    a("        endcase")
    a("    endfunction")
    a("")
    a("    function automatic bit rb_type_known(bit [31:0] t);")
    a('        return rb_type_name(t) != "UNKNOWN";')
    a("    endfunction")
    a("")
    a("endpackage : mqnic_ral_pkg")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    defs, blocks, common = parse()
    text = render(defs, blocks, common)

    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("STALE: ral/mqnic_ral_pkg.sv does not match mqnic_hw.h")
            print("Run: python sim/scripts/gen_ral.py")
            return 1
        print(f"RAL up to date: {len(blocks)} block type(s) from {HW_H.name}")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    n_reg = sum(len(b["regs"]) for b in blocks.values())
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  {len(blocks)} block type(s), {n_reg} register offset(s), "
          f"from {len(defs)} #defines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
